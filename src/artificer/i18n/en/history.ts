/**
 * The Reach's history in English (#1711, phase 4 of #1685): every sentence the story engine
 * (storytelling/render.ts, its event specs and arcs) writes for a Reach, the Artificer's own
 * sentences built on it (what villages and countries remember, world/remembered.ts and
 * regional-facts.ts; their recent local past, world/local-history.ts; the run's rumours of the past,
 * run-rumours.ts), and the words those sentences are made of.
 *
 * Why templates: the engine writes finished English, and its golden hashes (storytelling/testkit.ts)
 * are of that English, so it must not change, and the AI player and the API read it as it is. The
 * page reads each sentence back through these templates instead (artificer-app/sim-words.ts
 * `simLine`, with the history's parts from artificer-app/history-words.ts) and says it again in the
 * viewer's language. A sentence no template matches stays English rather than being guessed at;
 * history-i18n.test.ts lists the shapes known to fall through.
 *
 * The parts a history template can have (history-words.ts says how each is read):
 * - `{lord}` someone as the chronicle names them ("Ivar II of Hedlund", "an unknown figure"),
 *   `{given}` a bare given name, `{house}` a house, `{place}` a province or a region, `{fam}` a
 *   village family ("Brekke") and `{fams}` the family by its plural ("the Brekkes");
 * - `{title}` a lordship ("Hundred of Ravenford"), `{seats}` one with the seats that came with it
 *   ("Hundred of Ravenford and 2 other seats"), `{region}`/`{Region}` a region ("the Hollowford
 *   country", "the Timberwold"), lower- or upper-case where it stands;
 * - `{count}` a count of people or lands (digits, maybe grouped: "1,200"), `{year}` a year, `{n}` a
 *   decimal (a bread price);
 * - word lists by key: `{cause}` (`hist.cause.*`), `{madness}`, `{law}`, `{venture}` (`the lumber
 *   camp`, definite) and `{nventure}` (after "a new"), `{fled}`, `{noun}`/`{Noun}` (an event's name,
 *   `hist.noun.*`), `{share}`, `{setting}`, `{custom}`, `{trait}`, `{tier}`, `{drift}`, `{people}`,
 *   `{trade}`, `{founded}`, `{besides}`;
 * - `{line}` a whole sentence of its own (read on its own), and `{w}` one of the small words.
 * Every key is `hist.*`; the small words a local history picks among are `w.lh.*`.
 */

