// types.ts — the canonical data model. THIS is the source of truth.
//
// Core principle of the whole project: a structured simulation is canon; the
// LLM (later) is only a renderer. So these types must capture every fact a
// chronicler would need, with zero prose. Prose is derived, never stored.

// ---------------------------------------------------------------------------
// Primitive aliases — string IDs everywhere so cross-references are explicit.
// ---------------------------------------------------------------------------
export type CharId = string;
export type DynastyId = string;
export type ProvinceId = string;
export type TitleId = string;

export type Sex = "male" | "female";

// ---------------------------------------------------------------------------
// Psyche — the subjective worldview layer.
//
// Every character carries a Psyche. It has two tiers:
//   • biases  — chronic, low-to-moderate perceptual filters; continuous 0..1.
//               Everyone has all of them at varying intensity. Cultural and
//               faith seeds set baselines at birth; life events push them.
//   • distortion — an acute, severe break from reality (paranoid/megalomaniac/
//               zealot). Rare; onset is probabilistic, amplified by inbreeding.
//               Unlike biases, a distortion never self-corrects.
// ---------------------------------------------------------------------------
export type Distortion = "none" | "paranoid" | "megalomaniac" | "zealot";

export type PerceptualBias =
  // Cultural — seeded at birth from the dynasty's culture.
  | "honor_bound"        // slights demand satisfaction; lower REVENGE threshold
  | "fatalist"           // fear drive halved in practice; accepts losses as fate
  | "mercantile"         // reads relationships as transactional
  // Faith — seeded at birth from the dynasty's faith; stacks on cultural seeds.
  | "providential"       // divine attribution; surges after wins, blames enemies after losses
  | "doctrinal"          // faith-based in/out-group hardening; opinion floor vs heretics
  // Experience-acquired — pushed higher by specific life events.
  | "confirmation"       // hears what they want; inflates priority of desired goals
  | "wishful"            // perceives agreement in ambiguity; overestimates support
  | "betrayal_scarred"   // lone-wolf tendencies; no conspirators, high secrecy
  | "grief_locked"       // fear + vengeance amplified after major loss
  | "conqueror_confident"// overestimates own power after major win; resists defeat updates
  // Universal — everyone has a non-zero baseline; no natural ceiling.
  | "sunk_cost"          // abandoning investment feels wrong; escalates losing positions
  | "loss_aversion";     // losses sting ~2× more than equivalent gains feel good

export interface Psyche {
  distortion: Distortion;
  distortionOnsetYear: number | null;
  // All biases in [0,1]. Stored as a flat record so perception.ts can iterate
  // them generically and the type system catches any missing key at compile time.
  biases: Record<PerceptualBias, number>;
  // Computed once at birth from the family graph. Higher = more likely to develop
  // a distortion. 0 for seed characters whose parents aren't in the sim.
  inbreedingCoeff: number;
  // Year of the most recent title loss — gates the post-loss risk-seeking window
  // (loss_aversion drives reckless behaviour for ~5 years after dispossession).
  lastMajorLossYear: number | null;
}

// ---------------------------------------------------------------------------
// Drives — the motivational substrate. Each is 0..1. Goals are generated by
// reading drives against the world state (claims, scarcity, rivalries), so a
// character's personality is just this vector plus their circumstances.
// ---------------------------------------------------------------------------
export interface Drives {
  ambition: number; // want titles, power, expansion
  greed: number; // want wealth, resources
  vengeance: number; // act on grudges
  piety: number; // restraint; legitimacy-seeking
  lust: number; // marriage / heirs (kept light in v1)
  fear: number; // risk aversion / pre-emption
}

// ---------------------------------------------------------------------------
// Claim — a (possibly weak) right to a title. The engine of multigenerational
// war: succession losers are minted weak claims, which become their children's
// SEIZE_TITLE goals decades later.
// ---------------------------------------------------------------------------
export interface Claim {
  titleId: TitleId;
  strength: "strong" | "weak";
  basis: string; // human-readable origin, e.g. "passed over in 1183"
  year: number; // when the claim arose
}

// A grudge: minted when a scheme against someone is discovered, or a claim is
// denied. Feeds future vengeance-driven goals.
export interface Grudge {
  targetId: CharId;
  reason: string;
  year: number;
}

// A temporary peace or permanent defensive pact between two rulers. Truces are
// minted by the engine after wars; alliances form from sustained high opinion.
// Both are stored in World.treaties and queried by the goal and war systems.
export interface Treaty {
  id: string;
  type: "truce" | "alliance";
  partyA: CharId;
  partyB: CharId;
  startYear: number;
  expiresYear: number | null; // null = permanent (alliances)
}

export interface Character {
  id: CharId;
  name: string;
  sex: Sex;
  dynastyId: DynastyId;
  birthYear: number;
  deathYear: number | null;
  alive: boolean;
  causeOfDeath: string | null;

  // Family graph.
  fatherId: CharId | null;
  motherId: CharId | null;
  spouseId: CharId | null;
  childrenIds: CharId[];

  // Where the character resides / is seated (used by plague + famine).
  provinceId: ProvinceId;

  // Personality + accumulated history.
  drives: Drives;
  claims: Claim[];
  grudges: Grudge[];

  // Opinion of other characters, -100..100. Drives recruiting & conspiracy.
  opinion: Record<CharId, number>;

  // Social reputation, observed by others. A known schemer struggles to
  // recruit; reputation feeds the perception layer.
  reputation: {
    schemer: number; // 0..1, how known-treacherous they are
    just: number; // 0..1, reputation for fairness
  };

  // Subjective worldview — the perception/madness layer.
  psyche: Psyche;

  // Set true once a character has been promoted up from the pops (social
  // mobility / "breakout"). Lets the sifter spotlight low-born risers.
  lowborn: boolean;

  // A personal quirk (speech pattern, dress style, bearing) that, if the
  // character becomes a long-established ruler, can propagate into the culture's
  // aesthetic. null = none yet assigned. Set lazily by culture-drift.ts.
  quirk: string | null;

  // --- Magic / leveling layer ------------------------------------------------
  // Only exercised when World.magicEnabled. Kept on every Character (rather than
  // a side-map) so the base sim and the magic sim share one object shape; in
  // base mode these fields are simply initialised once and never touched.
  level: number; // power tier; 1 = an ordinary person
  lifeXp: number; // accumulated XP toward the next level
  charClass: CharClass; // current class — sets martial weight, XP rate, access
  comfort: number; // 0..1 safety+luxury; throttles XP and the will to risk
  ventured: boolean; // transient: sought danger this year (for the chronicle)

  // Optional — named skills earned by surviving specific trials (e.g. "dragon_slayer",
  // "void_walker"). Undefined for characters that never trial-earned anything, so
  // canonHash / base-sim JSON stays byte-identical. Populated only by challenges.ts.
  skills?: string[];

  // --- Personal skill premium & craft lineage --------------------------------
  // Wealth captured by personal skill (master craftsman charges premium). Unlike
  // Dynasty.wealth (dynastic), personalWealth dies with the character unless it
  // passes to an apprentice on death. Populated only when innovation.ts is active
  // (magicEnabled); otherwise stays 0 and is byte-identical to base sim.
  personalWealth: number;

  // A named craft-lineage link: master and apprentices. When the master dies,
  // top apprentice inherits personalWealth + level bump. Enables the "skill dies
  // with you unless you take a student" mechanic that Factor 2 depends on.
  mentorId: CharId | null;
  apprenticeIds: CharId[];

  // Guild membership — a character belongs to at most one guild at a time.
  // Only used when innovation.ts is active; null in base sim.
  guildId: GuildId | null;
}

// ---------------------------------------------------------------------------
// CultureState — the live, mutable overlay for a culture's current shape.
//
// CultureSpec (in world-spec.ts) is the immutable world bible. CultureState
// is what the sim keeps at runtime: which traits are active by tier, how much
// pressure is building, contested liminal states, and the aesthetic drift left
// by a long-ruling figure. Stored in World.liveCultures.
//
// Two pressure pools (elite/folk) converge at bleedRate = BLEED_BASE × (1 − stratification).
// Traits become CONTESTED when pressure crosses a threshold, then ESTABLISHED after
// `period` years — generational lag models how long real cultural change takes.
// ---------------------------------------------------------------------------
export interface CultureState {
  cultureId: string;
  // Separate pressure pools for lords (titled characters) and commons (untitled).
  elitePressure: Record<string, number>;
  folkPressure:  Record<string, number>;
  // Traits currently established in each tier.
  eliteTraits: Set<string>;
  folkTraits:  Set<string>;
  // Traits in the liminal contested zone (threshold crossed, not yet established).
  // Key: "elite:trait" | "folk:trait" | "elite:abandon:trait" | "folk:abandon:trait".
  contested: Record<string, { tier: "elite" | "folk"; trait: string; years: number; direction: "adopt" | "abandon" }>;
  // 0 = fluid society (tiers bleed freely); 1 = rigidly sealed.
  // Shaped by traits (caste_rigid/slavery push up, meritocracy pulls down) and events.
  stratification: number;
  // Permanent pressure-per-year from significant historical events; never decays.
  legacySeeds: Record<string, number>;
  // Years of continuous contact with neighbouring cultures (for folk contagion).
  contactYears: Record<string, number>;
  // Which (a-vs-b) rift pairs have already fired a CULTURAL_RIFT event.
  activeRifts: Set<string>;
  // Aesthetic drift — surface flavour shaped by a dominant figure's quirks.
  aesthetic: {
    linguisticShift: string | null; // e.g. "sibilant speech", "clipped consonants"
    fashionStyle:    string | null; // e.g. "elaborate fold-style", "austere simplicity"
  };
  // The current dominant figure (highest-tier title holder of this culture).
  establishedFigureId: string | null;
  // Year they became the dominant figure — quirks propagate after 20yr tenure.
  establishedSince: number;
  // Personal quirks assigned to characters so far (charId -> quirk string).
  figureQuirks: Record<string, string>;
  // Innovation ossification — set true by CANONICAL_ORTHODOXY_FROZEN, further
  // dampens invention probability for members of this culture. Post-Song Ming
  // Confucian pattern: canon-knowledge crowds out new-knowledge production.
  innovationOssified: boolean;
}

// Classes are tiered by how they're acquired:
//   common  — soft-gated, anyone can fall into them
//   mid     — capital-gated (wealth/knowledge ease the path)
//   rare    — rite-gated: only a house/guild that holds the rite can grant them
export type CharClass =
  | "commoner"
  | "soldier"
  | "hunter"
  | "knight"
  | "scholar"
  | "merchant"
  | "warden"
  | "stormcaller"
  | "necromancer";

// The rare classes — heritable "intellectual property" a dynasty can lose.
export type RareClass = "warden" | "stormcaller" | "necromancer";

export interface Dynasty {
  id: DynastyId;
  name: string;
  founderId: CharId;
  extinctYear: number | null; // set when the last member dies

  // --- Peoples layer (empty string = none; only used when the world defines
  // cultures/races/faiths). A house belongs to a people; its members inherit
  // that people's names, temperament, and faith.
  cultureId: string;
  raceId: string;
  faithId: string;

  // --- Magic / leveling layer (only used when World.magicEnabled) ----------
  wealth: number; // treasury; earned from lands, spent cultivating heirs
  rite: RareClass | null; // a heritable rare class-rite the house can grant
  riteBearerId: CharId | null; // the living master who can pass the rite on

  // --- Specialization layer (only used when World.magicEnabled) ------------
  // A house acquires an IDENTITY when its members concentrate in one class:
  // the mining house, the scholar house, the warrior house. Recomputed each
  // tick from member class distribution. `dominantClass` is null when no
  // class holds a majority of adult members. `specializationDepth` measures
  // (memberFraction × avgLevelInClass / 20), capped at 1 — a house with 80%
  // of its adults as level-15 scholars gets depth 0.6.
  //
  // `guildTradition` is a lazily-assigned flavor name that HOUSE_SPECIALIZES
  // sets and never changes. Together these drive the super-linear synergy
  // that makes an established house of masters dominate its craft.
  dominantClass: CharClass | null;
  specializationDepth: number;
  guildTradition: string | null;
}

// ---------------------------------------------------------------------------
// Guild — a persistent cross-dynasty organisation of same-craft masters. The
// engine already has GUILD_CHARTERED / GUILD_MONOPOLY_CLAIMED log events;
// Guild upgrades those to persistent entities with member rosters, treasury,
// and a mastership succession. Guilds bind APPRENTICES across dynastic lines,
// which is how personal craft-knowledge historically diffused faster than
// dynastic inheritance alone allowed.
// ---------------------------------------------------------------------------
export type GuildId = string;

export type GuildCraft =
  | "smithing"    // metallurgy / weaponsmith / armorer
  | "textiles"    // weaver / dyer
  | "trade"       // merchant / factor / banker
  | "letters"     // scholar / scribe / physician
  | "arms"        // knightly order / mercenary company
  | "arcana";     // rare-class holders (very rare, cross-dynasty)

export interface Guild {
  id: GuildId;
  name: string;                    // "Guild of Sunmeadow Weavers"
  craft: GuildCraft;
  provinceId: ProvinceId;          // guildhall / headquarters
  foundedYear: number;
  disbandedYear: number | null;
  masterId: CharId | null;         // current guildmaster (highest-level member)
  memberIds: CharId[];             // living members with matching craft
  wealth: number;                  // guild treasury
  monopolyInventionId: string | null; // if the guild monopolizes an invention
}

// ---------------------------------------------------------------------------
// Siege — persistent multi-year state for long sieges. Historical: Constantinople
// 1453 (7 weeks), Vienna 1683 (2 months), Alesia 52 BC (months), Masada 73 CE
// (months), the seige of Baghdad 1258 (13 days). The engine's one-shot WAR
// resolution can't model these — they need state that spans ticks, plus events
// mid-siege (sallies, breaches, starvation, plague-in-camp).
//
// Sieges are QUEUED from resolveWars when the target is kingdom-tier + close
// power ratio (attacker doesn't crush defender; defender doesn't overwhelm).
// Processed each tick by sieges.ts:runSieges — provisions and morale drop,
// random mid-siege events fire, termination checks fire.
// ---------------------------------------------------------------------------
export type SiegeId = string;

export interface Siege {
  id: SiegeId;
  attackerId: CharId;             // may die during siege
  defenderId: CharId;             // may die too — usually leads to fall
  provinceId: ProvinceId;         // the besieged province (defender's seat)
  titleId: TitleId;               // title being fought over
  startYear: number;
  yearsElapsed: number;           // 0 at siege start

  // Attrition dynamics — provisions runs out inside the walls; morale on both
  // sides declines slowly with events accelerating it.
  provisions: number;             // 0..1, defender food stores
  attackerMorale: number;         // 0..1
  defenderMorale: number;         // 0..1

  breached: boolean;              // walls breached — endgame conditions apply
  outcome: "active" | "fallen" | "lifted"; // "active" while running
}

// ---------------------------------------------------------------------------
// Climate — multi-decade climate phases. Historical: Medieval Warm Period
// (~950-1250), Little Ice Age (~1300-1850), the 8.2 ky cold event. Cold phases
// depress harvest yield and slow plague spread; warm phases boost harvest and
// speed plague. Phase transitions happen every 30-80 years on average.
//
// Guarded on `catastrophesEnabled` for RNG symmetry — the base sim without
// catastrophes stays byte-identical.
// ---------------------------------------------------------------------------
export type ClimatePhase = "cold" | "warm" | "neutral";

export interface Climate {
  phase: ClimatePhase;
  phaseStartYear: number;
  phaseDurationYears: number;    // typically 30-80
  severity: number;              // 0..1, how extreme the phase is
}

// ---------------------------------------------------------------------------
// TradeRoute — persistent entity that spans years. Formed when both endpoints
// have enough merchants + a shared conduit; grows in `wealth` while healthy;
// takes hits from shocks (siege, plague, famine, cold climate); dormant when
// wealth drops to 0; abandoned after 15 dormant years. Historical arcs: Silk
// Road (~200 BCE-1450 CE), Amber Road (~200 BCE-500 CE), Trans-Saharan
// (~700-1500). Composes with sieges (SIEGE_LAID at endpoint disrupts),
// climate (cold phase saps trade), and inventions (navigation boosts sea routes).
// ---------------------------------------------------------------------------
export type TradeRouteId = string;

export type TradeConduit = "sea" | "river" | "land";

export interface TradeRoute {
  id: TradeRouteId;
  fromProvinceId: ProvinceId;    // less-merchant end (dependent)
  toProvinceId: ProvinceId;      // more-merchant end (dominant)
  conduit: TradeConduit;
  foundedYear: number;
  closedYear: number | null;     // permanently abandoned
  dormantSince: number | null;   // wealth hit 0 in this year; may revive
  wealth: number;                // 0..1, current traffic/prosperity index
  peakWealth: number;            // highest wealth seen; used to detect FLOURISHES
  flourishesLoggedAt: number | null; // year FLOURISHES fired; prevents re-firing
  shockCount: number;            // lifetime disruption count
}

// ---------------------------------------------------------------------------
// Academy — persistent cross-dynasty organisation of scholar-masters.
// Historical: Al-Azhar (970 CE), Sorbonne (1150), Nalanda (5th century BCE),
// Timbuktu (1200s). Parallel to Guild but for letters — a bigger prestige
// horizon and magnet-effect on foreign scholars. Sacking or ossification can
// send scholars into diaspora (ACADEMY_MIGRATED — Byzantine → Italy pattern).
// ---------------------------------------------------------------------------
// ---------------------------------------------------------------------------
