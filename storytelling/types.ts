// ---------------------------------------------------------------------------
// Diseases — persistent, named strains with cross-immunity.
//
// PLAGUE (the one-shot event) is still fired for narrative shocks — famines
// and calamities. Named diseases are the LONGER arc: Black Death sweeps
// 1348, returns in 1361, mutates by 1400, burns out around 1600 as populations
// build resistance. Some strains are magical (rot-plague, mana-fever) and
// only appear in magic-enabled worlds — those defy cultural resistance and
// require magical medicine to counter.
// ---------------------------------------------------------------------------
export type DiseaseId = string;

export type DiseaseCategory = "mundane" | "magical";

export type DiseaseFamily =
  // Mundane families
  | "bubonic"       // Yersinia — bubonic / pneumonic plague
  | "hemorrhagic"   // Ebola / red-plague — high mortality, short outbreaks
  | "respiratory"   // consumption, tuberculosis — slow burn
  | "pox"           // smallpox — high mortality, permanent cross-immunity
  // Magical families
  | "mana_fever"    // hallucinatory fever that fires only in high-mana provinces
  | "rot_plague"    // necrotic — kills, then RAISES the dead (undead-raid vector)
  | "unraveling"    // devours language + memory in survivors
  | "choking_mist"; // a wrathful god's calling-card

export interface Disease {
  id: DiseaseId;
  name: string;                         // "the Ashen Cough", "the Ninefold Rot"
  category: DiseaseCategory;
  family: DiseaseFamily;
  lethality: number;                    // 0..1 base mortality per strike
  emergedYear: number;
  originProvinceId: ProvinceId | null;
  parentStrainId: DiseaseId | null;     // for mutations
  burnedOutYear: number | null;         // dormant after cross-immunity + fatigue
  strikeCount: number;                  // how many times it has struck
  immunisedCultures: string[];          // cultures with strong survival exposure
  totalDeaths: number;
}

// ---------------------------------------------------------------------------
// Languages — persistent, procedurally-named tongues attached to cultures.
//
// Every culture starts with a proto-language. Isolation drifts languages
// apart; sustained trade contact pulls them back together. Flourishing trade
// routes anoint a lingua franca — the hub culture's tongue becomes the
// working language of the whole route. Academies check for shared language;
// foreign scholars need translators.
//
// A language can DIE (last speaker culture goes extinct) and be REVIVED
// (scholars work from surviving treatises to reconstruct it — Sanskrit /
// Latin / Hebrew analog).
// ---------------------------------------------------------------------------
export type LanguageId = string;

export interface Language {
  id: LanguageId;
  name: string;                       // procedural — "Old Coastborn", "High Ibiki"
  cultureId: string | null;           // primary culture; null when it becomes a shared lingua franca
  parentId: LanguageId | null;        // parent language (family tree)
  bornYear: number;
  diedYear: number | null;            // last-speaker culture went extinct
  revivedYear: number | null;         // scholars reconstructed it from treatises
  driftScore: number;                 // 0..1 — distance from parent
  speakerCultures: string[];          // culture ids currently speaking this (for lingua franca)
  linguaFrancaRoutes: string[];       // trade-route ids where this language dominates
  writtenCorpus: number;              // 0..1 — quantity of surviving written material (for revival gating)
}

// ---------------------------------------------------------------------------
// Expeditions — Age-of-Discovery voyages that reach beyond the mapped world.
//
// A wealthy coastal port sponsors a captain with a fleet; the expedition
// heads over the horizon and, over several years, either returns with charts
// of unknown lands + exchange goods, is lost at sea, or is wrecked on a
// distant shore. Successful returns can unlock:
//   • NEW_LANDS_CHARTED — a marker discovery event
//   • FIRST_CONTACT_ESTABLISHED — the world learns of another culture
//   • GREAT_EXCHANGE — biological/cultural cross-pollination (Columbian analog)
//
// Composes with wildlife (new species carried back), disease (zoonotic
// crossings on return), and language (foreign tongues logged for future
// translation). Guarded on catastrophesEnabled so the golden-hash worlds
// see no expedition activity.
// ---------------------------------------------------------------------------
export type ExpeditionId = string;

export type ExpeditionStatus =
  | "launched"    // still at sea, unresolved
  | "returned"    // safely back to port
